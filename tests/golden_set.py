def rank_of(results, expected):
    """1-based позиция первого результата, чьё имя входит в expected; None, если не найден."""
    expected_lower = {e.lower() for e in expected}
    for i, name in enumerate(results, start=1):
        if name.lower() in expected_lower:
            return i
    return None


def evaluate(search_fn, golden_set=GOLDEN_SET, k=5, limit=10):
    """search_fn(query, limit, **extra_kwargs) -> список имён (str) в порядке выдачи.

    extra_kwargs берётся из GoldenQuery.extra_kwargs (например, language='sdbl' для
    проб языка запросов) и прокидывается в search_fn как есть.

    Возвращает (recall_at_k, mrr, подробности по каждому запросу).
    """
    details = []
    hits = 0
    reciprocal_sum = 0.0
    for gq in golden_set:
        results = list(search_fn(gq.query, limit, **gq.extra_kwargs))
        pos = rank_of(results, gq.expected)
        ok = pos is not None and pos <= k
        hits += int(ok)
        reciprocal_sum += (1.0 / pos) if pos else 0.0
        details.append(
            {
                "query": gq.query,
                "checks": gq.checks,
                "expected": gq.expected,
                "top": results[:k],
                "rank": pos,
                "hit_at_k": ok,
            }
        )
    n = len(golden_set)
    return (hits / n if n else 0.0), (reciprocal_sum / n if n else 0.0), details
