# фраза (нижний регистр) -> имена целевых элементов (ru), которые она должна поднимать.
# Сравнение — подстрока нормализованного запроса (syntax_db.py, T1), поэтому ключом
# может быть как одно слово, так и короткая фраза.
ALIASES = {
    "пустое": ("ЗначениеЗаполнено",),
    "пусто": ("ЗначениеЗаполнено",),
    "незаполнено": ("ЗначениеЗаполнено",),
    "содержит значение": ("ЗначениеЗаполнено",),
    "письмо": ("ИнтернетПочта", "ИнтернетПочтовоеСообщение"),
    "письма": ("ИнтернетПочта", "ИнтернетПочтовоеСообщение"),
    "емейл": ("ИнтернетПочта",),
    "email": ("ИнтернетПочта",),
    "обрезать": ("СокрЛП",),
    "в строку base64": ("Base64Строка",),
    "выбора данных": ("Предложение ВЫБРАТЬ",),
}


def rows():
    """Плоский список (phrase, target_name) для загрузки в таблицу alias."""
    return [(phrase, target) for phrase, targets in ALIASES.items() for target in targets]
